#include "p16f690.inc"

;CONSTS
POLYLOW EQU 0X21
POLYHIGH EQU 0X10   ;CRC16 POLYNOMIAL VALUE
 
INITLOW EQU 0XFF
INITHIGH EQU 0XFF   ;CRCSUM INIT VALUE


GLOBAL _CRC16

EXTERN _CRCSUM
EXTERN _DATAADDR
EXTERN _BYTENUM

PROG CODE

_CRC16:
	BCF STATUS, RP0
	BCF STATUS, RP1
	MOVF _BYTENUM, W
    	ADDWF _DATAADDR, W
    	MOVWF FSR
    
    	MOVLW INITLOW
    	MOVWF _CRCSUM
    	MOVLW INITHIGH
    	MOVWF _CRCSUM+1
    
BYTELOOP:
    	MOVF INDF,W
    	XORWF _CRCSUM+1,F
    	CALL PROCESSBITS
    	DECF FSR,W
    	MOVWF FSR
    	SUBWF _DATAADDR,W
	SUBLW 0X00
	ADDLW 0x01
    	BTFSS STATUS,Z
    	GOTO BYTELOOP
    
    	RETURN

PROCESSBITS:   
    	BTFSS _CRCSUM+1,7
    	GOTO MSBC0
    
    	BCF STATUS,C
    	RLF _CRCSUM,F
    	RLF _CRCSUM+1,F
    	BCF STATUS,C
    
   	MOVLW POLYLOW
    	XORWF _CRCSUM,F
    	MOVLW POLYHIGH
    	XORWF _CRCSUM+1,F
    
    	GOTO DONEMSBS0
    
MSBC0:
    	BCF STATUS,C
   	RLF _CRCSUM,F
    	RLF _CRCSUM+1,F

DONEMSBS0:

    	BTFSS _CRCSUM+1,7
    	GOTO MSBC1
    
